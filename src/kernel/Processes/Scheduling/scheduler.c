extern void _switch_threads(tcb_t *tcb);

// holds the tcb currently at the top of the queue
tcb_t *top_tcb = NULL;
// holds the tcb that is last in the waiting queue
tcb_t *last_tcb = NULL;
// the currently switched to pcb
tcb_t *running_tcb = NULL;

tcb_t dummy_tcb = {0};

uint64_t thread_count = 0;


/**
 * returns the next thread in the queue.
 * modifies state of
 * - top & last_tcb
 * - entries around selection
 */
tcb_t * scheduler_pick_next_thread() {
    tcb_t *active_tcb = top_tcb;
    tcb_t *pointing_tcb = NULL;                  // tcb preceding active_tcb

    while (active_tcb) {
        if (active_tcb->state != PROCESS_READY ) {
            active_tcb = active_tcb->next;
            continue;
        }

        if (active_tcb->active_priority != 0) {
            --active_tcb->active_priority;             // sneaky speed??
            pointing_tcb = active_tcb;
            active_tcb = active_tcb->next;
            continue;
        }
        if (active_tcb == top_tcb)
            pointing_tcb = NULL;

        goto selected_task;
    }
    // nothing found for 0 priority so choose first ready in queue
    active_tcb = top_tcb;
    while (active_tcb && active_tcb->state != PROCESS_READY)
        active_tcb = active_tcb->next;

    if (!active_tcb){       // last has next ptr to NULL
        // wait for the next interrupt if no tasks exists
        __asm volatile ("sti");
        lapic_write(LAPIC_EOI, 0);
        while (1)
            ;
    }

    pointing_tcb = NULL;            // no prev

    selected_task:
        active_tcb->active_priority = active_tcb->priority + 1;
        active_tcb->state = PROCESS_RUNNING;

        if (pointing_tcb == NULL)
            top_tcb = active_tcb->next;
        else
            pointing_tcb->next = active_tcb->next;

        // put it last in queue
        last_tcb->next = active_tcb;
        last_tcb = active_tcb;
        last_tcb->next = NULL;

    return active_tcb;
}

/**
 * switches from the currently running thread to next_tcb
 * @param next_tcb thread to switch to
 * @param frame generated by the interrupt it contains mostly registers
 */
void context_switch(tcb_t *next_tcb, struct interrupt_frame *frame) {
    Imemcpy(
        &running_tcb->regsiters,
        &frame->gpo_regs,
        sizeof(cpu_reg_frame)
    );
    Imemcpy(
        (void *) &running_tcb->regsiters + sizeof(cpu_reg_frame),
        &frame->cpu_regs,
        sizeof(cpu_push_frame)
        );

    //Iprintf("pre: %x\n", next_tcb->page_table);
    //test_walk_table((void *) KERNEL_PHYS_TO_VIRT(next_tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    // change pml4 table (it still has the kernel mappings so the current code should stay fine)
    write_cr3((uint64_t)next_tcb->page_table);
    Iprintf("code segment: (%x)\n", next_tcb->regsiters.psp.rip);
    Iprintf("firstB (%x)", *(uint8_t *)PROCESS_CODE_VIRT_ADDR);


    running_tcb = next_tcb;
    // send the EOI as late as possible
    lapic_write(LAPIC_EOI, 0);
    _switch_threads(next_tcb);
}

/**
 * initializes the scheduler and adds the kernel as the first task
 */
void scheduler_init(tcb_t * tcb) {
    //minimal init for the dummy thread
    dummy_tcb.state = PROCESS_DENIED;     // make sure process doesn't get scheduled
    dummy_tcb.priority = 0;

    running_tcb = &dummy_tcb;
    last_tcb = &dummy_tcb;
    last_tcb->next = NULL;

    top_tcb = tcb;
    //test_walk_table((void *)KERNEL_PHYS_TO_VIRT(tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    top_tcb->next = last_tcb;
    tcb->state = PROCESS_READY;
}



void scheduler_add_thread(tcb_t *tcb) {
    __asm volatile ("cli");
    last_tcb->next = tcb;
    last_tcb = tcb;
    last_tcb->next = NULL;
}

