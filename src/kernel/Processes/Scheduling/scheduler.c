extern void _switch_threads(tcb_t *tcb);

// holds the tcb currently at the top of the queue
tcb_t *top_tcb = NULL;
// holds the tcb that is last in the waiting queue (last.next = NULL)
tcb_t *last_tcb = NULL;
// the currently switched to pcb
tcb_t *running_tcb = NULL;

tcb_t dummy_tcb = {0};

uint64_t thread_count = 0;
/**
 * returns the next thread in the queue.
 * modifies state of
 * - top & last_tcb
 * - entries around selection
 */
tcb_t * scheduler_pick_next_thread(INTERRUPT_SRC src) {
    tcb_t *active_tcb = top_tcb;
    tcb_t *pointing_tcb = NULL;                  // tcb preceding active_tcb

    while (active_tcb) {
        if (active_tcb->state != THREAD_READY ) {
            active_tcb = active_tcb->next;
            continue;
        }

        if (active_tcb->active_priority != 0) {
            --active_tcb->active_priority;             // sneaky speed??
            pointing_tcb = active_tcb;
            active_tcb = active_tcb->next;
            continue;
        }
        if (active_tcb == top_tcb)
            pointing_tcb = NULL;

        goto selected_task;
    }
    // nothing found for 0 priority so choose lowest ready in queue
    active_tcb = top_tcb;
    // first find a tcb that is ready
    while (active_tcb && active_tcb->state != THREAD_READY)
        active_tcb = active_tcb->next;

    // whole proc is skipped if iter == null
    pointing_tcb = NULL;            // no prev
    tcb_t * iter = active_tcb;
    tcb_t * prev = NULL;            // no prev
    // could do a check for 1 as next low but not sure if trade off is worth it
    while (iter) {
        if (iter->state == THREAD_READY && active_tcb->active_priority > iter->active_priority) {
            Iprintf("technically eligble[%i]: (%x, state: %x)\n",iter->active_priority, iter, iter->state);
            active_tcb = iter;      // choose highest
            pointing_tcb = prev;
        }

        prev = iter;
        iter = iter->next;
    }

    if (!active_tcb){       // last has next ptr to NULL (no task is ready)
        Iprintf("none found\n");
        switch (src) {
            // no ready task at all so check if the currently running task can be ran again.
            //TODO: expand for more interrupts
            case INT_TMR: {
                active_tcb = last_tcb;
                // is already in the correct position js update the priority
                active_tcb->active_priority = active_tcb->priority + 1;
                return active_tcb;
            }
            default:
                goto wait;
        }
        wait:
        // wait for the next interrupt if no tasks exists
        __asm volatile ("sti");
        lapic_write(LAPIC_EOI, 0);
        while (1)
            ;
    }

    selected_task:
        //Iprintf("found task: %x (pml: %x, %x)\n", active_tcb, active_tcb->page_table, active_tcb->active_priority);
        active_tcb->active_priority = active_tcb->priority + 1;
        active_tcb->state = THREAD_RUNNING;

        if (pointing_tcb == NULL)
            top_tcb = active_tcb->next;
        else
            pointing_tcb->next = active_tcb->next;

        // put it last in queue
        last_tcb->next = active_tcb;
        last_tcb = active_tcb;
        last_tcb->next = NULL;

    //__asm__ volatile ("cli; hlt");
    return active_tcb;
}

/**
 * switches from the currently running thread to next_tcb
 * @param next_tcb thread to switch to
 * @param frame generated by the interrupt it contains mostly registers
 */
void context_switch(tcb_t *next_tcb, struct interrupt_frame *frame, INTERRUPT_SRC src) {
    Imemcpy(
        &running_tcb->regsiters,
        &frame->gpo_regs,
        sizeof(cpu_reg_frame)
    );
    Imemcpy(
        (void *) &running_tcb->regsiters + sizeof(cpu_reg_frame),
        &frame->cpu_regs,
        sizeof(cpu_push_frame)
        );

    if (running_tcb != &dummy_tcb) {        // don't change state of dummy bc it has NULL val
        //TODO: expand for other sources
        switch (src) {
            case INT_TMR: {
                running_tcb->state = THREAD_READY;
            }
            default: {
                running_tcb->state = THREAD_READY;
            };
        }
    }


    next_tcb->state = THREAD_RUNNING;
    //Iprintf("pre: %x\n", next_tcb->page_table);
    //test_walk_table((void *) KERNEL_PHYS_TO_VIRT(next_tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    // change pml4 table (it still has the kernel mappings so the current code should stay fine)
    write_cr3((uint64_t)next_tcb->page_table);
    // Iprintf("thread: (%x)\n", next_tcb->tid);
    // Iprintf("calla (%x)", *(uint8_t *)THREAD_CODE_VIRT_ADDR);


    running_tcb = next_tcb;
    // send the EOI as late as possible
    lapic_write(LAPIC_EOI, 0);
    _switch_threads(next_tcb);
}

/**
 * initializes the scheduler and adds the kernel as the first task
 */
void scheduler_init(tcb_t * tcb) {
    //minimal init for the dummy thread
    dummy_tcb.state = THREAD_DENIED;     // make sure process doesn't get scheduled
    dummy_tcb.priority = 0;

    running_tcb = &dummy_tcb;
    last_tcb = &dummy_tcb;
    last_tcb->next = NULL;

    top_tcb = tcb;
    //test_walk_table((void *)KERNEL_PHYS_TO_VIRT(tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    top_tcb->next = last_tcb;
    tcb->state = THREAD_READY;
    ++thread_count;
}


/**
 * adds a thread to the scheduler and disables ints
 */
void scheduler_add_thread(tcb_t *tcb) {
    __asm volatile ("cli");
    last_tcb->next = tcb;
    last_tcb = tcb;
    last_tcb->next = NULL;
    ++thread_count;
}

void schedule(struct interrupt_frame *frame, INTERRUPT_SRC src) {
    tcb_t * next = scheduler_pick_next_thread(src);
    context_switch(next, frame, src);
}

/**
 * removes a thread and disables ints
 */
void stop_thread(tcb_t * tcb) {
    __asm volatile ("cli");
}


tcb_t * spawn_thread(
    PID_t parent,
    bool is_priviledged,
    uint16_t priority,
    thread_memory_supply_block_t mem_supply_block,
    thread_memory_permission_info_t perms
) {
    tcb_t * tcb = create_thread(parent, is_priviledged, priority);
    //TODO: find a way to cleanly handle return from thread_supply_mem
    thread_supply_mem(tcb, mem_supply_block, perms);
    tcb->state =THREAD_READY;
    scheduler_add_thread(tcb);
    return tcb;
}

tcb_t * spawn_alloc_thread(
    PID_t parent,
    bool is_priviledged,
    uint16_t priority,
    thread_memory_allocation_info_t *alloc_info,
    thread_memory_permission_info_t *perms,
    thread_memory_supply_block_t *supply
) {
    tcb_t * tcb = create_thread(parent, is_priviledged, priority);
    //TODO: find a way to cleanly handle return from thread_supply_mem
    thread_supply_new_mem(tcb, alloc_info, perms, supply);
    tcb->state = THREAD_READY;
    scheduler_add_thread(tcb);
    return tcb;
}