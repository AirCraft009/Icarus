static inline uint16_t saturating_sub16(uint16_t a, uint16_t b)
{
    return a >= b ? a - b : 0;
}

static inline uint16_t saturating_dec16(uint16_t a)
{
    return a >= 1 ? a - 1 : 0;
}

extern void _switch_threads(cpu_regs *regs);

// holds the tcb currently at the top of the queue
tcb_t *top_tcb = NULL;
// holds the tcb that is last in the waiting queue (last.next = NULL)
tcb_t *last_tcb = NULL;
// the currently switched to pcb
tcb_t *running_tcb = NULL;

tcb_t dummy_tcb = {0};

uint64_t thread_count = 0;
/**
 * returns the next thread in the queue.
 * modifies state of
 * - top & last_tcb
 * - entries around selection
 */
tcb_t * scheduler_pick_next_thread(INTERRUPT_SRC src) {
    tcb_t *active_tcb = top_tcb;
    tcb_t *best_tcb = active_tcb;
    uint16_t max_priority = UINT16_MAX;

    while (active_tcb) {
        if (active_tcb->state != THREAD_READY ) {
            active_tcb = active_tcb->next;
            continue;
        }

        if (active_tcb->active_priority >= max_priority) {
            active_tcb->active_priority = saturating_dec16(active_tcb->active_priority);             // sneaky speed??
            active_tcb = active_tcb->next;
            continue;
        }

        best_tcb = active_tcb;
        active_tcb->active_priority = saturating_dec16(active_tcb->active_priority);        // still decrease priority bc
        max_priority = active_tcb->active_priority;
        active_tcb = active_tcb->next;
    }




    if (max_priority == UINT16_MAX){       // last has next ptr to NULL (no task is ready)
        Iprintf("none found\n");
        switch (src) {
            // no ready task at all so check if the currently running task can be ran again.
            //TODO: expand for more interrupts
            case INT_TMR: {
                best_tcb = last_tcb;
                // is already in the correct position js update the priority
                best_tcb->active_priority = best_tcb->priority + 1;
                return best_tcb;
            }
            default:
                goto wait;
        }
        wait:
        // wait for the next interrupt if no tasks exists
        __asm volatile ("sti");
        lapic_write(LAPIC_EOI, 0);
        while (1)
            ;
    }

    //Iprintf("{SELECTED TASK: %x (pml: %x, %x)}\n", best_tcb->tid, best_tcb, best_tcb->active_priority);
    best_tcb->active_priority = best_tcb->priority + 1;
    best_tcb->state = THREAD_RUNNING;

    if (best_tcb->prev == NULL) {       // is top
        top_tcb = best_tcb->next;
        top_tcb->prev = NULL;
    }
    else if (best_tcb->next == NULL) {  // is last
        return best_tcb;                // correct position alr
    }
    else {
        // swap ptrs
        best_tcb->prev->next = best_tcb->next;
        best_tcb->next->prev = best_tcb->prev;
    }


    // put it last in queue
    last_tcb->next = best_tcb;
    best_tcb->prev = last_tcb;
    best_tcb->next = NULL;
    last_tcb = best_tcb;
    return best_tcb;
}

/**
 * switches from the currently running thread to next_tcb
 * @param next_tcb thread to switch to
 * @param frame generated by the interrupt it contains mostly registers
 */
void context_switch(tcb_t *next_tcb, struct interrupt_frame *frame, INTERRUPT_SRC src) {
    Imemcpy(
        &running_tcb->registers,
        &frame->gpo_regs,
        sizeof(cpu_reg_frame)
    );
    Imemcpy(
        (void *) &running_tcb->registers + sizeof(cpu_reg_frame),
        &frame->cpu_regs,
        sizeof(cpu_push_frame)
        );

    if (running_tcb != &dummy_tcb) {        // don't change state of dummy bc it has NULL val
        //TODO: expand for other sources
        switch (src) {
            Iprintf("setting");
            case INT_TMR: {
                running_tcb->state = THREAD_READY;
            }
            default: {
                running_tcb->state = THREAD_READY;
            };
        }
    }


    next_tcb->state = THREAD_RUNNING;
    //Iprintf("pre: %x\n", next_tcb->page_table);
    //test_walk_table((void *) KERNEL_PHYS_TO_VIRT(next_tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    // change pml4 table (it still has the kernel mappings so the current code should stay fine)
    write_cr3((uint64_t)next_tcb->page_table);
    // Iprintf("calla (%x)", *(uint8_t *)THREAD_CODE_VIRT_ADDR);


    running_tcb = next_tcb;
    // send the EOI as late as possible
    lapic_write(LAPIC_EOI, 0);
    // Iprintf("thread cs: (%x)\n",* ((uint8_t *) &next_tcb->registers + 128));
    // Iprintf("thread ss: (%x)\n",* ((uint8_t *) &next_tcb->registers + 152));
    //TODO: restore stack ptr to frame and add 16.
    _switch_threads(&next_tcb->registers);
}

/**
 * initializes the scheduler and adds the kernel as the first task
 */
void scheduler_init(tcb_t * tcb) {
    //minimal init for the dummy thread
    dummy_tcb.state = THREAD_DENIED;     // make sure process doesn't get scheduled
    dummy_tcb.priority = 0;

    running_tcb = &dummy_tcb;
    last_tcb = &dummy_tcb;
    last_tcb->next = NULL;
    last_tcb->prev = tcb;

    top_tcb = tcb;
    //test_walk_table((void *)KERNEL_PHYS_TO_VIRT(tcb->page_table), (void *)KERNEL_PHYS_TO_VIRT(2 * HUGE_PS));
    top_tcb->next = last_tcb;
    top_tcb->prev = NULL;
    tcb->state = THREAD_READY;
    ++thread_count;
}


/**
 * adds a thread to the scheduler and disables ints
 */
void scheduler_add_thread(tcb_t *tcb) {
    __asm volatile ("cli");
    last_tcb->next = tcb;
    tcb->prev = last_tcb;
    tcb->next = NULL;
    last_tcb = tcb;
    ++thread_count;
}

void schedule(struct interrupt_frame *frame, INTERRUPT_SRC src) {
    tcb_t * next = scheduler_pick_next_thread(src);
    context_switch(next, frame, src);
}

/**
 * removes a thread and disables ints
 */
void stop_thread(tcb_t * tcb) {
    __asm volatile ("cli");
}


